/* Build us-apportionment.geojson: the House-seat cartogram, states scaled so
 * drawn area is proportional to 2020-census seats, placed on the hand-drawn
 * slots and relaxed until nothing overlaps.
 *
 * This does not reimplement the cartogram. It runs the real solver -- the same
 * solver.js + studio.worker.js pair that powers the interactive studio at
 * jcervas.github.io/maps/cartogram-studio/ -- headless in Node, with the
 * studio's own default parameters (areaDivisor 2.9, padding 2 px, hand-drawn
 * slots, Figma tweaks on, New England grouped). The one deliberate difference:
 * seatKey is "2020" (the 2020-census apportionment) rather than the UI default
 * "districts"; for the 50 states the two are the same 435 seats.
 *
 * Inputs, all committed in raw/ (copied from the cartograms repo, see
 * PROVENANCE.tsv):
 *   raw/solver.js          the solver: placement, relaxation
 *   raw/studio.worker.js   the pipeline that drives it
 *   raw/studio.json        geometry + seats, generated by the R build
 *
 * Output frame: 1152 x 748.8, y down (SVG convention). Coordinates are
 * pre-projected plane units; draw with d3.geoIdentity() or base-R polygon().
 *
 * RUN FROM INSIDE geo/:  node build-apportionment.js
 */
"use strict";

const fs = require("fs");
const path = require("path");
const { performance } = require("perf_hooks");

const RAW = path.join(__dirname, "raw");
const SEAT_KEY = "2020";

/* ---- a just-enough Web Worker shim, so the worker file runs unmodified.
 * new Function() evaluates in global scope, so `self` must be a true global. */
globalThis.self = globalThis;
self.performance = performance;
self.importScripts = (f) => {
  new Function(fs.readFileSync(path.join(RAW, f), "utf8")).call(self);
};

let result = null, error = null;
self.postMessage = (m) => {
  if (m.type === "error") error = m.message;
  if (m.type === "done") result = m.result;
};

new Function(fs.readFileSync(path.join(RAW, "studio.worker.js"), "utf8")).call(self);

/* ---- run the pipeline exactly as the studio does ---- */
const payload = JSON.parse(fs.readFileSync(path.join(RAW, "studio.json"), "utf8"));

self.onmessage({ data: { type: "init", payload } });
self.onmessage({
  data: {
    type: "solve",
    id: 1,
    params: {
      seatKey: SEAT_KEY,
      areaDivisor: payload.defaults.areaDivisor,   // 2.9
      padding: payload.defaults.padding,           // 2 px
      tweaks: true,
      groupNE: true,
      placement: "auto",                           // hand-drawn slots
      cellMode: "none",                            // states only, no district cells
      seed: payload.defaults.seed,
      pointsPerSeat: payload.defaults.pointsPerSeat,
      balanceIters: payload.defaults.balanceIters,
    },
  },
});

if (error) throw new Error("solver: " + error);
if (!result) throw new Error("solver returned nothing");
const st = result.place;
if (!st.converged)
  throw new Error("placement did not converge (unmet " + st.unmet + " px)");
console.log(
  `placed ${result.bodies.length} states: mode=${st.mode}, ` +
  `${st.iterations} iterations, max drift ${st.moved.toFixed(1)} px ` +
  `(cap ${st.maxShift.toFixed(0)}), fidelity error ${st.fidelity.error.toFixed(1)}%`
);

/* ---- apply each body's transform to its outline; emit GeoJSON ---- */
const r1 = (v) => Math.round(v * 10) / 10;
const byId = Object.fromEntries(result.bodies.map((b) => [b.st, b]));

const seatTotal = payload.states.reduce((a, s) => a + s.seats[SEAT_KEY], 0);
if (seatTotal !== 435) throw new Error("seats sum to " + seatTotal + ", not 435");

const features = payload.states.map((s) => {
  const b = byId[s.st];
  const tf = ([x, y]) => [r1(x * b.scale + b.tx), r1(y * b.scale + b.ty)];
  const g = s.outline;
  const coords =
    g.type === "Polygon"
      ? [g.coordinates.map((ring) => ring.map(tf))]
      : g.coordinates.map((part) => part.map((ring) => ring.map(tf)));
  return {
    type: "Feature",
    properties: {
      st: s.st,
      fips: s.fips,
      name: s.name,
      seats: s.seats[SEAT_KEY],
      seats_2000: s.seats["2000"],
      seats_2010: s.seats["2010"],
      seats_2020: s.seats["2020"],
      seats_2030: s.seats["2030"],
      // the studio anchors labels at the scaled centroid; do the same
      label_x: r1(s.centroid[0] * b.scale + b.tx),
      label_y: r1(s.centroid[1] * b.scale + b.ty),
    },
    geometry: { type: "MultiPolygon", coordinates: coords },
  };
});

const fc = {
  type: "FeatureCollection",
  frame: { width: 1152, height: 748.8, y: "down" },
  note:
    "House apportionment cartogram: drawn area proportional to " + SEAT_KEY +
    "-census seats. Pre-projected plane coordinates; no DC (no voting seat). " +
    "Solved by the cartogram-studio solver, defaults, seatKey " + SEAT_KEY + ".",
  features,
};

fs.writeFileSync(
  path.join(__dirname, "us-apportionment.geojson"),
  JSON.stringify(fc)
);
console.log(`wrote us-apportionment.geojson (${features.length} states, ${seatTotal} seats)`);

/* The studio outlines carry 0.5 px-quantisation self-intersections; repair
 * them so this file is as valid as the TIGER-derived ones. See the R file. */
require("child_process").execFileSync("Rscript", ["repair-apportionment.R"], {
  cwd: __dirname,
  stdio: "inherit",
});
